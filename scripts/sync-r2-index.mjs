#!/usr/bin/env node
/**
 * Sync R2 object indexes from the configured bucket:
 *   - data/r2VideoIndex.ts   ← flat `{postId}.mp4` (and similar)
 *   - data/r2ThumbIndex.ts   ← `thumbnail/{postId}.jpg` (and similar)
 *
 * Usage: node scripts/sync-r2-index.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ListObjectsV2Command, S3Client } from "@aws-sdk/client-s3";

function loadEnv() {
  const path = resolve(process.cwd(), ".env");
  try {
    const raw = readFileSync(path, "utf8");
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const eq = trimmed.indexOf("=");
      if (eq <= 0) continue;
      const key = trimmed.slice(0, eq).trim();
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      if (!(key in process.env)) process.env[key] = value;
    }
  } catch {
    /* optional */
  }
}

loadEnv();

const accountId = process.env.R2_ACCOUNT_ID?.trim();
const accessKeyId = process.env.R2_ACCESS_KEY_ID?.trim();
const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY?.trim();
const bucket = process.env.R2_BUCKET_NAME?.trim();

if (!accountId || !accessKeyId || !secretAccessKey || !bucket) {
  console.error("Missing R2_* env vars in .env");
  process.exit(1);
}

const client = new S3Client({
  region: "auto",
  endpoint: `https://${accountId}.r2.cloudflarestorage.com`,
  credentials: { accessKeyId, secretAccessKey },
});

const keys = [];
let token;

do {
  const out = await client.send(
    new ListObjectsV2Command({
      Bucket: bucket,
      Prefix: "",
      ContinuationToken: token,
      MaxKeys: 1000,
    })
  );
  for (const obj of out.Contents ?? []) {
    if (obj.Key) keys.push(obj.Key);
  }
  token = out.IsTruncated ? out.NextContinuationToken : undefined;
} while (token);

const VIDEO_RE = /^(\d+)\.(mp4|MP4|mov|MOV|webm|WEBM|m4v|M4V)$/;
const THUMB_RE = /^thumbnail\/(\d+)\.(jpe?g|JPE?G|png|PNG|webp|WEBP)$/;

/** postId -> exact object key (e.g. "168" -> "168.MP4") */
const videoKeys = {};
/** postId -> exact object key (e.g. "32" -> "thumbnail/32.jpg") */
const thumbKeys = {};

for (const key of keys) {
  const videoMatch = key.match(VIDEO_RE);
  if (videoMatch) {
    videoKeys[videoMatch[1]] = key;
    continue;
  }
  const thumbMatch = key.match(THUMB_RE);
  if (thumbMatch) {
    thumbKeys[thumbMatch[1]] = key;
  }
}

const videoPostIds = Object.keys(videoKeys).sort((a, b) => Number(a) - Number(b));
const thumbPostIds = Object.keys(thumbKeys).sort((a, b) => Number(a) - Number(b));
const synced = new Set([...Object.keys(videoKeys), ...Object.keys(thumbKeys)]);
const skipped = keys.filter((key) => {
  if (VIDEO_RE.test(key) || THUMB_RE.test(key)) return false;
  // Ignore folder placeholders
  if (key.endsWith("/")) return false;
  return true;
});

const now = new Date().toISOString();

const videoOutPath = resolve(process.cwd(), "data/r2VideoIndex.ts");
const videoBody = `/**
 * Auto-generated by scripts/sync-r2-index.mjs — do not edit by hand.
 * Re-run after uploading new {postId}.mp4 files to R2.
 * Last sync: ${now}
 */
export const R2_VIDEO_KEYS: Record<string, string> = ${JSON.stringify(videoKeys, null, 2)};

export const R2_VIDEO_POST_IDS = new Set<string>(Object.keys(R2_VIDEO_KEYS));

export function hasR2Video(postId: string) {
  return R2_VIDEO_POST_IDS.has(postId.trim());
}

export function getR2VideoKey(postId: string) {
  return R2_VIDEO_KEYS[postId.trim()];
}
`;
writeFileSync(videoOutPath, videoBody, "utf8");

const thumbOutPath = resolve(process.cwd(), "data/r2ThumbIndex.ts");
const thumbBody = `/**
 * Auto-generated by scripts/sync-r2-index.mjs — do not edit by hand.
 * Re-run after uploading new thumbnail/{postId}.jpg files to R2.
 * Last sync: ${now}
 */
export const R2_THUMB_KEYS: Record<string, string> = ${JSON.stringify(thumbKeys, null, 2)};

export const R2_THUMB_POST_IDS = new Set<string>(Object.keys(R2_THUMB_KEYS));

export function hasR2Thumb(postId: string) {
  return R2_THUMB_POST_IDS.has(postId.trim());
}

export function getR2ThumbKey(postId: string) {
  return R2_THUMB_KEYS[postId.trim()];
}
`;
writeFileSync(thumbOutPath, thumbBody, "utf8");

console.log(
  `Wrote ${videoOutPath} (${videoPostIds.length} videos) and ${thumbOutPath} (${thumbPostIds.length} thumbs) from ${keys.length} bucket objects`
);
if (skipped.length) {
  console.log(`Skipped ${skipped.length} object(s) (not video/{id}.mp4 or thumbnail/{id}.jpg):`);
  for (const k of skipped.slice(0, 40)) console.log(`  - ${k}`);
  if (skipped.length > 40) console.log(`  … +${skipped.length - 40} more`);
}

function missingBetween(ids) {
  if (!ids.length) return [];
  const maxId = Number(ids[ids.length - 1]);
  const set = new Set(ids);
  const missing = [];
  for (let n = 1; n <= maxId; n++) {
    if (!set.has(String(n))) missing.push(n);
  }
  return missing;
}

const missingVideos = missingBetween(videoPostIds);
const missingThumbs = missingBetween(thumbPostIds);
if (missingVideos.length) {
  console.log(
    `Missing ${missingVideos.length} video id(s) between 1–${videoPostIds[videoPostIds.length - 1]}: ${missingVideos.slice(0, 25).join(", ")}${missingVideos.length > 25 ? ", …" : ""}`
  );
}
if (missingThumbs.length) {
  console.log(
    `Missing ${missingThumbs.length} thumb id(s) between 1–${thumbPostIds[thumbPostIds.length - 1]}: ${missingThumbs.slice(0, 25).join(", ")}${missingThumbs.length > 25 ? ", …" : ""}`
  );
}

void synced;
